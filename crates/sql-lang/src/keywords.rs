#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn structural_list_is_sorted_for_binary_search() {
        assert!(STRUCTURAL.windows(2).all(|w| w[0] < w[1]));
    }

    #[test]
    fn reserved_words_per_dialect() {
        assert!(is_reserved("select", Dialect::Postgres));
        assert!(is_reserved("User", Dialect::Postgres));
        assert!(is_reserved("key", Dialect::Mysql));
        assert!(is_reserved("rank", Dialect::Mysql));
        assert!(!is_reserved("rank", Dialect::Postgres));
        assert!(is_reserved("percent", Dialect::Mssql));
        assert!(is_reserved("pragma", Dialect::Sqlite));
        for common in ["name", "id", "date", "status", "type", "value", "email"] {
            for d in Dialect::ALL {
                assert!(!is_reserved(common, d), "{common} {d:?}");
            }
        }
    }
}
