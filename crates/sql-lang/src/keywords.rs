fn contains(list: &[&str], upper: &str) -> bool {
    list.contains(&upper)
}

fn upper(word: &str) -> Option<String> {
    (word.len() <= 32).then(|| word.to_ascii_uppercase())
}

/// A keyword that structures a query: never an alias, never an operand.
pub fn is_structural(word: &str) -> bool {
    upper(word).is_some_and(|u| STRUCTURAL.binary_search(&u.as_str()).is_ok())
}

/// A word that can't be used as a bare identifier in `d`.
pub fn is_reserved(word: &str, d: Dialect) -> bool {
    let Some(u) = upper(word) else { return false };
    let u = u.as_str();
    STRUCTURAL.binary_search(&u).is_ok()
        || contains(COMMON_RESERVED, u)
        || match d {
            Dialect::Mysql => contains(MYSQL_RESERVED, u),
            Dialect::Mssql => contains(MSSQL_RESERVED, u),
            Dialect::Sqlite => contains(SQLITE_RESERVED, u),
            Dialect::Postgres => false,
        }
}

/// Keywords that end an operand (a literal or a niladic function) rather than expect one.
pub fn is_value_keyword(word: &str) -> bool {
    [
        "NULL",
        "TRUE",
        "FALSE",
        "END",
        "CURRENT_DATE",
        "CURRENT_TIME",
        "CURRENT_TIMESTAMP",
        "CURRENT_USER",
        "LOCALTIME",
        "LOCALTIMESTAMP",
        "SESSION_USER",
        "USER",
    ]
    .iter()
    .any(|k| k.eq_ignore_ascii_case(word))
}

